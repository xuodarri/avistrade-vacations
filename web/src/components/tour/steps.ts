/**
 * Шаги тура «Помощь» по экранам — только данные, разметку экранов они не трогают.
 * Якорь шага — атрибут `data-tour="…"` на элементе экрана. Если элемента нет (пустой список,
 * панель ещё закрыта), шаг пропускается. Список якорей для владельцев экранов — README.md рядом.
 */
import type { Placement } from "@floating-ui/react";

export type TourRole = "employee" | "manager" | "hr";

export interface TourStep {
  /** Якорь: элемент с `data-tour="anchor"`. */
  anchor: string;
  /** Запасной CSS-селектор, если якоря на странице нет. */
  fallback?: string;
  title: string;
  text: string;
  /** Где ставить карточку; у края экрана она всё равно перевернётся. По умолчанию снизу. */
  placement?: Placement;
  /** Если цели нет — нажать на этот якорь (или CSS-селектор) и подождать её: так открывается панель заявки.
   *  Если якорь — цель другого шага этого тура, берётся и его запасной селектор. */
  reveal?: string;
}

export interface TourDef {
  /** Экран: ключ в localStorage вместе с ролью. */
  id: string;
  path: string;
  steps: TourStep[];
}

