export const tourFor = (path: string | null) => TOURS.find((t) => t.path === path);

export const roleOf = (access: readonly string[] = []): TourRole =>
  access.includes("hr") ? "hr" : access.includes("manager") ? "manager" : "employee";

/** Якорь или готовый CSS-селектор. */
export const toSelector = (x: string) => (/^[\w.-]+$/.test(x) ? `[data-tour="${x}"]` : x);
